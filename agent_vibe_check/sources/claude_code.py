"""
Claude Code transcripts.

    ~/.claude/projects/<cwd-slug>/<session-uuid>.jsonl

Each line is one event. Conversation lines have `type` "user" or "assistant"
and an Anthropic-style `message` with `content` (str or list of blocks).
One API response is often split across several assistant lines that share
`message.id`; we merge those back into one Message.

Skipped by default:
  - sessions started by the Agent SDK (`entrypoint` "sdk-*"): scripts, not a human;
  - sidechain lines and `<session>/subagents/*.jsonl` (the human directs the parent);
  - sessions whose cwd is a temp dir or scratchpad.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Iterator

import re

from ..parser import Message, ToolCall
from .base import SourceInfo, is_noise_cwd, make_session

SOURCE = "claude_code"

# Text Claude Code injects into user turns. None of it was typed by the person.
_DROP_PREFIXES = (
    "<task-notification>",          # background task / subagent finished
    "<local-command-stdout>",       # output of a local slash command
    "<local-command-stderr>",
    "<local-command-caveat>",
    "Caveat: The messages below were generated by the user while running local commands",
    "This session is being continued from a previous conversation",  # compaction summary
)
_REMINDER_RE = re.compile(r"<system-reminder>.*?</system-reminder>", re.DOTALL)
_CMD_NAME_RE = re.compile(r"<command-name>(.*?)</command-name>", re.DOTALL)
_CMD_ARGS_RE = re.compile(r"<command-args>(.*?)</command-args>", re.DOTALL)
_BASH_IN_RE = re.compile(r"<bash-input>(.*?)</bash-input>", re.DOTALL)
_BASH_OUT_RE = re.compile(r"<bash-(?:stdout|stderr)>(.*?)</bash-(?:stdout|stderr)>", re.DOTALL)


def clean_user_text(text: str) -> tuple[str | None, str | None]:
    """
    Return (typed_text, tool_output) for one user text block.
    - injected harness text -> (None, None)
    - "/command args" typed by the person -> ("/command args", None)
    - "! cmd" shell input -> ("! cmd", None); its stdout -> (None, output)
    """
    t = _REMINDER_RE.sub("", text).strip()
    if not t or t.startswith(_DROP_PREFIXES):
        return None, None
    m = _CMD_NAME_RE.search(t)
    if m:
        args = _CMD_ARGS_RE.search(t)
        cmd = m.group(1).strip() + (" " + args.group(1).strip() if args and args.group(1).strip() else "")
        return cmd, None
    m = _BASH_IN_RE.search(t)
    if m:
        return "! " + m.group(1).strip(), None
    if t.startswith(("<bash-stdout>", "<bash-stderr>")):
        out = "\n".join(x.strip() for x in _BASH_OUT_RE.findall(t))
        return None, out
    return t, None


def default_root() -> Path:
    env = os.environ.get("CLAUDE_CONFIG_DIR")
    base = Path(env) if env else Path.home() / ".claude"
    return base / "projects"


def iter_transcript_files(root: Path) -> Iterator[Path]:
    if not root.is_dir():
        return
    for project_dir in sorted(root.iterdir()):
        if project_dir.is_dir():
            yield from sorted(project_dir.glob("*.jsonl"))


def _add_text(role: str, text: str, text_blocks: list[str], tool_results: list[dict]) -> None:
    if role != "user":
        text_blocks.append(text)
        return
    typed, output = clean_user_text(text)
    if typed:
        text_blocks.append(typed)
    if output:
        tool_results.append({"type": "tool_result", "content": output})


def _blocks_to_message(role: str, content) -> Message:
    text_blocks: list[str] = []
    tool_calls: list[ToolCall] = []
    tool_results: list[dict] = []
    if isinstance(content, str):
        if content:
            _add_text(role, content, text_blocks, tool_results)
    elif isinstance(content, list):
        for b in content:
            if not isinstance(b, dict):
                continue
            t = b.get("type")
            if t == "text" and b.get("text"):
                _add_text(role, b["text"], text_blocks, tool_results)
            elif t == "tool_use":
                tool_calls.append(ToolCall.from_block(b))
            elif t == "tool_result":
                tool_results.append(b)
    return Message(role=role, text_blocks=text_blocks,
                   tool_calls=tool_calls, tool_results=tool_results)


def parse_file(path: Path, include_automated: bool = False) -> "Session | None":
    messages: list[Message] = []
    cwd: str | None = None
    entrypoint: str | None = None
    last_assistant_id: str | None = None
    started_at: str | None = None
    session_id = path.stem

    try:
        fh = path.open("r", encoding="utf-8", errors="replace")
    except OSError:
        return None
    with fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            try:
                obj = json.loads(line, strict=False)
            except json.JSONDecodeError:
                continue
            kind = obj.get("type")
            if kind not in ("user", "assistant"):
                continue
            if obj.get("isSidechain") or obj.get("isMeta") or obj.get("isCompactSummary"):
                continue
            cwd = cwd or obj.get("cwd")
            started_at = started_at or obj.get("timestamp")
            entrypoint = entrypoint or obj.get("entrypoint")
            session_id = obj.get("sessionId") or session_id
            msg = obj.get("message") or {}
            m = _blocks_to_message(kind, msg.get("content"))
            if not (m.text_blocks or m.tool_calls or m.tool_results):
                continue

            mid = msg.get("id") if kind == "assistant" else None
            if mid and mid == last_assistant_id and messages and messages[-1].role == "assistant":
                prev = messages[-1]
                prev.text_blocks.extend(m.text_blocks)
                prev.tool_calls.extend(m.tool_calls)
                continue
            last_assistant_id = mid
            messages.append(m)

    if not include_automated and (entrypoint or "").startswith("sdk"):
        return None
    if is_noise_cwd(cwd):
        return None
    return make_session(
        session_id=session_id,
        cwd=cwd,
        fallback_folder=path.parent.name.lstrip("-"),
        path=path,
        messages=messages,
        source=SOURCE,
        started_at=started_at,
    )


class ClaudeCodeSource:
    key = SOURCE

    def __init__(self, root: Path | None = None, include_automated: bool = False):
        self.root = root or default_root()
        self.include_automated = include_automated

    def info(self) -> SourceInfo:
        n = sum(1 for _ in iter_transcript_files(self.root))
        return SourceInfo(
            key=self.key, label="Claude Code", vendor="Anthropic",
            docs_url="https://code.claude.com/docs/en/overview",
            roots=[self.root], session_count=n,
        )

    def files(self) -> Iterator[Path]:
        return iter_transcript_files(self.root)

    def parse(self, path: Path) -> "Session | None":
        return parse_file(path, include_automated=self.include_automated)

    def iter_sessions(self) -> Iterator["Session"]:
        for path in self.files():
            s = self.parse(path)
            if s is not None:
                yield s
